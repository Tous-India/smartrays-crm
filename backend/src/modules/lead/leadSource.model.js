import mongoose from "mongoose";

const leadSourceSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

const LeadSource = mongoose.model("LeadSource", leadSourceSchema);

export default LeadSource;
